    # ------------------------------------------------------------------
    # Generic rendering helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _render_kv_table(rows: Sequence[Tuple[str, str]]) -> str:
        """Render a two-column key/value table.

        The key column is bolded by the caller; this helper only
        emits the table skeleton and escapes cells. Rows whose value
        is already preformatted (contains Markdown markup) should be
        passed through unchanged; the caller is responsible for
        escaping.
        """
        if not rows:
            return ""
        lines = ["| Field | Value |", "| --- | --- |"]
        for key, value in rows:
            if value is None or value == "":
                value = _NOT_AVAILABLE
            lines.append(f"| {_escape_table_cell(key)} | {value} |")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Counting helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _count_reproduced(findings: Sequence[ReportFinding]) -> int:
        total = 0
        for finding in findings:
            if MarkdownReporter._is_reproduced(finding) is True:
                total += 1
        return total

    @staticmethod
    def _is_reproduced(finding: ReportFinding) -> Optional[bool]:
        """Return True/False/None depending on the reproduction status."""
        status = getattr(finding, "reproduction_status", None)
        if status is None:
            return None
        text = str(status).strip().lower()
        if text == "reproduced":
            return True
        if text in ("not_reproduced", "failed"):
            return False
        return None

    @staticmethod
    def _count_classifications(
        findings: Sequence[ReportFinding],
    ) -> Dict[str, int]:
        counts: Dict[str, int] = {}
        for finding in findings:
            key = (
                getattr(finding, "classification_label", None)
                or getattr(finding, "classification", None)
                or getattr(finding, "crash_kind", None)
                or "unclassified"
            )
            key_str = str(key)
            counts[key_str] = counts.get(key_str, 0) + 1
        return counts

    # ------------------------------------------------------------------
    # Representation
    # ------------------------------------------------------------------

    def __repr__(self) -> str:
        opts = self._options
        return (
            f"MarkdownReporter(include_toc={opts.include_toc}, "
            f"include_summary={opts.include_summary}, "
            f"include_metadata_json={opts.include_metadata_json})"
        )


