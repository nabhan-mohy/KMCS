    # Supplemental sections
    # ------------------------------------------------------------------

    def _render_supplemental(
        self,
        sections: Sequence[Tuple[str, str]],
    ) -> str:
        if not sections:
            return ""
        parts: List[str] = []
        for title, body in sections:
            anchor = _slugify_anchor(title)
            parts.append(f'<a id="{anchor}"></a>')
            parts.append(f"## {_heading_text(title)}")
            if body:
                parts.append(body)
        return "\n\n".join(parts)

    # ------------------------------------------------------------------
    # Report data section
    # ------------------------------------------------------------------

    def _render_metadata_json(self, bundle: ReportBundle) -> str:
        try:
            if hasattr(bundle, "to_dict"):
                payload = bundle.to_dict()
            else:
                payload = {
                    "metadata": getattr(bundle.metadata, "to_dict", lambda: {})()  # type: ignore[union-attr]
                    if bundle.metadata is not None else None,
                    "findings": [
                        f.to_dict() for f in (bundle.findings or ())
                        if hasattr(f, "to_dict")
                    ],
                }
            text = json.dumps(payload, indent=2, sort_keys=True, default=str)
        except Exception as exc:  # noqa: BLE001
            return (
                "## Report data\n\n"
                f"> Failed to serialise report data: {_escape_text(str(exc))}"
            )

        block = _code_block(
            text, lang="json", fence_char=self._options.fence_char
        )

        if self._options.use_details_blocks:
            return (
                '<a id="report-data"></a>\n'
                "## Report data\n\n"
                "<details>\n"
                "<summary>Underlying bundle as JSON</summary>\n\n"
                f"{block}\n\n"
                "</details>"
            )
        return '<a id="report-data"></a>\n## Report data\n\n' + block

