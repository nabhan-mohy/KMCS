# Escaping helpers
# ---------------------------------------------------------------------------


_BACKTICK_RUN_RE = re.compile(r"`+")


def _max_backtick_run(text: str) -> int:
    """Return the length of the longest backtick run in ``text``.

    Returns zero when the text contains no backticks.
    """
    longest = 0
    for match in _BACKTICK_RUN_RE.finditer(text):
        length = match.end() - match.start()
        if length > longest:
            longest = length
    return longest


def _escape_text(value: Any) -> str:
    """Escape a value for inclusion in a Markdown paragraph.

    The escaping is intentionally minimal: Markdown paragraphs are
    forgiving, and over-escaping produces ugly output. The function
    only escapes characters that could change paragraph structure:
    leading ``#``, leading ``-`` followed by a space, leading ``>``,
    and leading digits followed by a period (ordered-list syntax).
    """
    if value is None:
        return _NOT_AVAILABLE
    if isinstance(value, (list, tuple, set, frozenset)):
        if not value:
            return _NOT_AVAILABLE
        return ", ".join(_escape_text(v) for v in value)
    text = str(value)
    if not text:
        return ""
    # Collapse newlines to spaces so that a multi-line value does not
    # accidentally become a multi-line paragraph with its own
    # structure.
    text = text.replace("\r\n", " ").replace("\r", " ").replace("\n", " ")
    # Escape structural prefixes.
    stripped = text.lstrip()
    if stripped.startswith("#"):
        text = "\\" + text.lstrip()
    elif stripped.startswith(">"):
        text = "\\" + text.lstrip()
    elif re.match(r"^\s*-\s", text) or re.match(r"^\s*\*\s", text):
        text = "\\" + text.lstrip()
    elif re.match(r"^\s*\d+\.\s", text):
        # Escape the dot so it becomes a literal number-dot.
        text = re.sub(r"^(\s*\d+)\.", r"\1\\.", text)
    return text


def _escape_table_cell(value: Any) -> str:
    """Escape a value for inclusion in a Markdown table cell.

    GFM tables do not allow literal pipe characters in cell content;
    pipes must be escaped with a backslash. Newlines are not allowed
    at all; the reporter converts them to ``<br>`` tags, which every
    GFM renderer interprets as a line break inside the cell.
    """
    if value is None:
        return _NOT_AVAILABLE
    if isinstance(value, (list, tuple, set, frozenset)):
        if not value:
            return _NOT_AVAILABLE
        return ", ".join(_escape_table_cell(v) for v in value)
    text = str(value)
    # Normalise line endings before processing.
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # Escape pipes first (before we introduce <br>).
    text = text.replace("|", "\\|")
    # Convert newlines to <br>.
    text = text.replace("\n", "<br>")
    # Escape backslash-newline sequences that could be left over.
    # (Not needed in practice, but harmless.)
    return text


def _inline_code(value: Any) -> str:
    """Render ``value`` as inline code.

    The number of surrounding backticks is chosen so that the value's
    own backticks cannot terminate the span early. When the value
    starts or ends with a backtick, GFM requires a space between the
    delimiters and the content; the function adds one.
    """
    if value is None:
        return _NOT_AVAILABLE
    text = str(value)
    if not text:
        return "``"
    longest = _max_backtick_run(text)
    ticks = "`" * max(1, longest + 1)
    if text.startswith("`") or text.endswith("`"):
        return f"{ticks} {text} {ticks}"
    return f"{ticks}{text}{ticks}"


def _code_block(
    value: Any,
    *,
    lang: str = "",
    fence_char: str = DEFAULT_FENCE_CHAR,
) -> str:
    """Render ``value`` as a fenced code block.

    The fence length is chosen to be at least three and always at
    least one longer than the longest run of the fence character in
    the value. This guarantees the block cannot be closed early by
    its own content.

    A trailing newline is appended to the value if it does not
    already end with one, so that the closing fence always begins on
    its own line.
    """
    if value is None:
        return ""
    text = str(value)
    # Normalise line endings.
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    longest = _max_backtick_run(text) if fence_char == "`" else _longest_run(text, fence_char)
    fence = fence_char * max(3, longest + 1)
    opening = f"{fence}{lang}" if lang else fence
    if not text.endswith("\n"):
        text = text + "\n"
    return f"{opening}\n{text}{fence}"


def _longest_run(text: str, char: str) -> int:
    """Return the length of the longest run of ``char`` in ``text``."""
    if not text or not char:
        return 0
    longest = 0
    current = 0
    for c in text:
        if c == char:
            current += 1
            if current > longest:
                longest = current
        else:
            current = 0
    return longest


def _heading_text(value: Any) -> str:
    """Sanitise a value for use as heading content.

    Headings cannot contain newlines; the function collapses them to
    spaces. Leading and trailing whitespace is stripped. Other
    characters are preserved.
    """
    if value is None:
        return ""
    text = str(value)
    text = text.replace("\r\n", " ").replace("\r", " ").replace("\n", " ")
    return text.strip()


def _escape_link_text(value: Any) -> str:
    """Escape a value for use as the text portion of a Markdown link."""
    if value is None:
        return ""
    text = str(value)
    # Bracket characters must be escaped inside link text.
    text = text.replace("[", "\\[").replace("]", "\\]")
    # Collapse newlines.
    text = text.replace("\r\n", " ").replace("\r", " ").replace("\n", " ")
    return text


def _escape_link_target(value: Any) -> str:
    """Escape a value for use as the target of a Markdown link.

    Targets in GFM may contain most characters if wrapped in angle
    brackets; for simplicity the reporter percent-encodes spaces and
    angle brackets, which are the two characters most likely to cause
    trouble in practice.
    """
    if value is None:
        return ""
    text = str(value)
    text = text.replace(" ", "%20")
    text = text.replace("<", "%3C").replace(">", "%3E")
    return text


