@dataclass(frozen=True)
class MarkdownOptions:
    """Immutable options for :class:`MarkdownReporter`.

    Attributes
    ----------
    include_toc:
        When True (default), emit a table of contents after the
        header.
    include_summary:
        When True (default), emit a summary section with derived
        counts.
    include_metadata_json:
        When True (default), emit the underlying bundle as pretty-
        printed JSON inside a collapsible block at the end of the
        report.
    include_raw_output:
        When True (default), include each finding's raw crash output
        inside a collapsible block.
    use_details_blocks:
        When True (default), wrap verbose content in ``<details>``
        blocks. GitHub, GitLab, and Gitea render these as native
        collapsible sections.
    max_output_chars:
        Per-finding cap on the number of characters of raw output
        included. ``None`` disables the cap.
    trailing_newline:
        When True (default), append a single newline to the end of
        the rendered document.
    fence_char:
        Character used for fenced code blocks. Defaults to a
        backtick. Overriding this is rarely necessary; it exists for
        callers that target a non-CommonMark renderer.
    max_table_cell_length:
        Optional cap on the length of a single table cell. Longer
        values are truncated. ``None`` disables the cap. This is
        useful when rendering into terminals with narrow widths.
    """

    include_toc: bool = DEFAULT_INCLUDE_TOC
    include_summary: bool = DEFAULT_INCLUDE_SUMMARY
    include_metadata_json: bool = DEFAULT_INCLUDE_METADATA_JSON
    include_raw_output: bool = True
    use_details_blocks: bool = DEFAULT_USE_DETAILS_BLOCKS
    max_output_chars: Optional[int] = DEFAULT_MAX_OUTPUT_CHARS
    trailing_newline: bool = DEFAULT_TRAILING_NEWLINE
    fence_char: str = DEFAULT_FENCE_CHAR
    max_table_cell_length: Optional[int] = None

    def __post_init__(self) -> None:
        if self.max_output_chars is not None and self.max_output_chars < 0:
            raise ValueError("max_output_chars must be non-negative or None")
        if self.max_table_cell_length is not None and self.max_table_cell_length < 0:
            raise ValueError(
                "max_table_cell_length must be non-negative or None"
            )
        if not self.fence_char:
            raise ValueError("fence_char must not be empty")
        if len(self.fence_char) != 1:
            raise ValueError("fence_char must be a single character")


