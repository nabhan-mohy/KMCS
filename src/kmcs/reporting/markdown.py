class MarkdownError(Exception):
    """Base class for all Markdown reporter errors."""


class MarkdownValidationError(MarkdownError):
    """Raised when a bundle fails pre-render validation.

    Validation is limited to conditions that would produce a
    malformed document: missing title, findings with no identifier,
    duplicate finding identifiers.
    """


class MarkdownSerializationError(MarkdownError):
    """Raised when a value in the bundle cannot be rendered.

    In practice this exception is rare: the reporter is deliberately
    permissive about the shapes of values it accepts. It is raised
    only when a value cannot be coerced to text at all.
    """


