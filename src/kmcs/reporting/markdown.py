    def _render_toc(self, bundle: ReportBundle) -> str:
        entries: List[Tuple[str, str]] = []
        if self._options.include_summary:
            entries.append(("summary", "Summary"))
        if bundle.campaign is not None:
            entries.append(("campaign", "Campaign"))
        if bundle.corpus is not None:
            entries.append(("corpus", "Corpus"))
        if bundle.findings:
            entries.append(("findings", "Findings"))
            entries.append(("findings-overview", "Findings overview"))
        for title, _ in bundle.supplemental_sections:
            entries.append((_slugify_anchor(title), title))
        if self._options.include_metadata_json:
            entries.append(("report-data", "Report data"))

        if len(entries) < 2:
            return ""

        lines = ["## Table of contents", ""]
        for anchor, label in entries:
            lines.append(f"- [{_escape_link_text(label)}](#{anchor})")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Summary
    # ------------------------------------------------------------------

    def _render_summary(self, bundle: ReportBundle) -> str:
        findings = bundle.findings or ()
        total = len(findings)

        severity_counts = {name: 0 for name in _SEVERITY_LEVELS}
        for finding in findings:
            level = _severity_level_name(getattr(finding, "severity", None))
            severity_counts[level] = severity_counts.get(level, 0) + 1

        reproduced = self._count_reproduced(findings)

        rows: List[Tuple[str, str]] = []
        rows.append(("Total findings", str(total)))
        for level_name in ("critical", "high", "medium", "low", "informational"):
            count = severity_counts.get(level_name, 0)
            if count or level_name in ("critical", "high"):
                rows.append((level_name.capitalize(), str(count)))
        unknown = severity_counts.get("unknown", 0)
        if unknown:
            rows.append(("Unclassified", str(unknown)))
        if total:
            rows.append(("Reproduced", f"{reproduced} / {total}"))

        body = [self._render_kv_table(rows)]

        if total == 0:
            body.insert(
                0,
                "> This report contains no findings. The bundle was "
                "rendered successfully; there were no finding records "
                "to include.",
            )

        # Classification breakdown when more than one classification
        # is present, since otherwise it duplicates the severity table.
        classification_counts = self._count_classifications(findings)
        if len(classification_counts) > 1:
            rows_c: List[Tuple[str, str]] = []
            for name, count in sorted(
                classification_counts.items(),
                key=lambda kv: (-kv[1], kv[0]),
            ):
                rows_c.append((name, str(count)))
            body.append("### By classification")
            body.append(self._render_kv_table(rows_c))

        return "\n\n".join(["## Summary"] + body)

