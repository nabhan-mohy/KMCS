    # ------------------------------------------------------------------
    # Findings
    # ------------------------------------------------------------------

    def _render_findings(
        self, findings: Sequence[ReportFinding]
    ) -> str:
        sorted_findings = self._sort_findings(findings)

        parts: List[str] = [f"## Findings ({len(sorted_findings)})"]
        parts.append(self._render_findings_overview(sorted_findings))
        for idx, finding in enumerate(sorted_findings):
            parts.append(self._render_finding(finding, idx))

        return "\n\n".join(parts)

    @staticmethod
    def _sort_findings(
        findings: Sequence[ReportFinding],
    ) -> List[ReportFinding]:
        """Return findings sorted by severity then by discovery time.

        Severity ordering is the canonical order defined by
        :data:`_SEVERITY_ORDER`. Within a severity level, findings
        are ordered by discovery time (newest first). Ties are broken
        by finding identifier to guarantee determinism.
        """
        def key(f: ReportFinding) -> Tuple[int, float, str]:
            level = _severity_level_name(getattr(f, "severity", None))
            sev_rank = _SEVERITY_ORDER.get(level, 99)
            discovered = getattr(f, "discovered_at", None)
            if isinstance(discovered, datetime):
                ts = -discovered.timestamp()
            else:
                ts = 0.0
            fid = str(getattr(f, "finding_id", ""))
            return (sev_rank, ts, fid)

        return sorted(findings, key=key)

    def _render_findings_overview(
        self, findings: Sequence[ReportFinding]
    ) -> str:
        """Render the summary table that precedes the detailed findings."""
        if not findings:
            return ""
        header = (
            "| # | Severity | Finding | Classification | Reproduced |\n"
            "| --- | --- | --- | --- | --- |"
        )
        lines = [header]
        for idx, finding in enumerate(findings):
            level = _severity_level_name(getattr(finding, "severity", None))
            severity_display = {
                "critical": "**Critical**",
                "high": "**High**",
                "medium": "Medium",
                "low": "Low",
                "informational": "Informational",
                "unknown": "_unclassified_",
            }.get(level, "_unclassified_")

            title = getattr(finding, "title", "") or ""
            anchor = f"finding-{_slugify_anchor(str(getattr(finding, 'finding_id', idx)))}"
            title_link = f"[{_escape_link_text(title)}](#{anchor})"

            classification = (
                getattr(finding, "classification_label", None)
                or getattr(finding, "classification", None)
                or getattr(finding, "crash_kind", None)
            )
            classification_cell = (
                _escape_table_cell(classification)
                if classification is not None
                else _NOT_AVAILABLE
            )

            reproduced = self._is_reproduced(finding)
            reproduced_cell = "yes" if reproduced else "no" if reproduced is False else _NOT_AVAILABLE

            lines.append(
                f"| {idx + 1} | {severity_display} | {title_link} | "
                f"{classification_cell} | {reproduced_cell} |"
            )
        return "\n".join(lines)

    def _render_finding(self, finding: ReportFinding, index: int) -> str:
        """Render a single finding as a top-level subsection."""
        fid = str(getattr(finding, "finding_id", f"finding-{index}"))
        anchor_id = f"finding-{_slugify_anchor(fid)}"

        level = _severity_level_name(getattr(finding, "severity", None))
        badge = _severity_badge(level)
        title = _heading_text(getattr(finding, "title", "") or f"Finding {index + 1}")

        parts: List[str] = []
        # Explicit anchor so that the overview table's links resolve
        # regardless of how the renderer slugifies the heading.
        parts.append(f'<a id="{anchor_id}"></a>')
        parts.append(f"### {badge} {title}")
        parts.append(f"**Finding ID:** {_inline_code(fid)}")

        overview_rows = self._finding_overview_rows(finding)
        if overview_rows:
            parts.append(self._render_kv_table(overview_rows))

        process = self._render_finding_process(finding)
        if process:
            parts.append(process)

        source = self._render_finding_source(finding)
        if source:
            parts.append(source)

        stack = self._render_finding_stack(finding)
        if stack:
            parts.append(stack)

        repro = self._render_finding_reproduction(finding)
        if repro:
            parts.append(repro)

        evidence = self._render_finding_evidence(finding)
        if evidence:
            parts.append(evidence)

        notes = self._render_finding_notes(finding)
        if notes:
            parts.append(notes)

        metadata = self._render_finding_metadata(finding)
        if metadata:
            parts.append(metadata)

        return "\n\n".join(parts)

    def _finding_overview_rows(
        self, finding: ReportFinding
    ) -> List[Tuple[str, str]]:
        rows: List[Tuple[str, str]] = []

        def add(label: str, value: str) -> None:
            rows.append((label, value))

        severity_raw = getattr(finding, "severity", None)
        if severity_raw is not None:
            level = _severity_level_name(severity_raw)
            display = {
                "critical": "**Critical**",
                "high": "**High**",
                "medium": "Medium",
                "low": "Low",
                "informational": "Informational",
                "unknown": "_unclassified_",
            }.get(level, _escape_table_cell(severity_raw))
            add("Severity", display)

        crash_kind = getattr(finding, "crash_kind", None)
        if crash_kind is not None:
            add("Crash kind", _inline_code(crash_kind))

        classification_label = getattr(finding, "classification_label", None)
        classification = getattr(finding, "classification", None)
        if classification_label is not None:
            add("Classification", _escape_table_cell(classification_label))
        elif classification is not None:
            add("Classification", _inline_code(classification))

        sanitizer = getattr(finding, "sanitizer", None)
        if sanitizer is not None:
            add("Sanitizer", _inline_code(sanitizer))

        fingerprint = getattr(finding, "fingerprint", None)
        if fingerprint is not None:
            add("Fingerprint", _inline_code(fingerprint))

        digest = getattr(finding, "input_digest", None)
        if digest is not None:
            add("Input digest", _inline_code(digest))

        size = getattr(finding, "input_size", None)
        if size is not None:
            add("Input size", _format_bytes(size))

        path = getattr(finding, "input_path", None)
        if path is not None:
            add("Input path", _inline_code(path))

        discovered = getattr(finding, "discovered_at", None)
        if discovered is not None:
            add("Discovered", _format_datetime(discovered))

        discovered_by = getattr(finding, "discovered_by", None)
        if discovered_by is not None:
            add("Discovered by", _escape_table_cell(discovered_by))

        tags = getattr(finding, "tags", None) or frozenset()
        if tags:
            add("Tags", _escape_table_cell(", ".join(sorted(tags))))

        return rows

    def _render_finding_process(self, finding: ReportFinding) -> str:
        rows: List[Tuple[str, str]] = []

        exit_code = getattr(finding, "exit_code", None)
        if exit_code is not None:
            rows.append(("Exit code", _inline_code(exit_code)))

        signal_number = getattr(finding, "signal_number", None)
        signal_name = getattr(finding, "signal_name", None)
        if signal_number is not None or signal_name is not None:
            if signal_name and signal_number is not None:
                cell = f"{_inline_code(signal_name)} ({_escape_table_cell(signal_number)})"
            elif signal_name:
                cell = _inline_code(signal_name)
            else:
                cell = _inline_code(signal_number)
            rows.append(("Signal", cell))

        timed_out = getattr(finding, "timed_out", None)
        if timed_out is not None:
            rows.append(("Timed out", "yes" if timed_out else "no"))

        fault = getattr(finding, "fault_address", None)
        if fault is not None:
            rows.append(("Fault address", _inline_code(fault)))

        access = getattr(finding, "access_type", None)
        if access is not None:
            rows.append(("Access type", _inline_code(access)))

        if not rows:
            return ""
        return "#### Process\n\n" + self._render_kv_table(rows)

    def _render_finding_source(self, finding: ReportFinding) -> str:
        location = getattr(finding, "source_location", None)
        if not location or not isinstance(location, Mapping):
            return ""
        file_ = location.get("file")
        line = location.get("line")
        column = location.get("column")
        function = location.get("function")

        parts: List[str] = []
        if function:
            parts.append(_inline_code(function))
        if file_:
            location_text = str(file_)
            if line is not None:
                location_text += f":{line}"
                if column is not None:
                    location_text += f":{column}"
            parts.append(_inline_code(location_text))
        if not parts:
            return ""
        return "#### Source location\n\n" + " at ".join(parts)

    def _render_finding_stack(self, finding: ReportFinding) -> str:
        frames = getattr(finding, "stack_frames", None) or ()
        if not frames:
            return ""
        rows: List[str] = []
        for idx, frame in enumerate(frames):
            if not isinstance(frame, Mapping):
                rows.append((str(idx), _escape_table_cell(frame), "", ""))
                continue
            function = frame.get("function") or frame.get("func") or ""
            file_ = frame.get("file") or frame.get("filename") or ""
            line = frame.get("line") or frame.get("lineno") or ""
            offset = frame.get("offset") or frame.get("pc") or ""
            location_cell = str(file_)
            if line:
                location_cell += f":{line}"
            rows.append(
                (
                    str(idx),
                    _escape_table_cell(function),
                    _escape_table_cell(location_cell) if location_cell else _NOT_AVAILABLE,
                    _escape_table_cell(offset) if offset else _NOT_AVAILABLE,
                )
            )

        lines = [
            "#### Stack trace",
            "",
            "| # | Function | Location | Offset |",
            "| --- | --- | --- | --- |",
        ]
        for idx, function, location, offset in rows:
            lines.append(f"| {idx} | {function} | {location} | {offset} |")
        return "\n".join(lines)

    def _render_finding_reproduction(self, finding: ReportFinding) -> str:
        rows: List[Tuple[str, str]] = []

        repro_status = getattr(finding, "reproduction_status", None)
        if repro_status is not None:
            rows.append(("Reproduction", self._status_cell(repro_status)))

        attempts = getattr(finding, "reproduction_attempts", None)
        matched = getattr(finding, "reproduction_matched", None)
        if attempts is not None or matched is not None:
            if attempts is not None and matched is not None:
                rows.append(
                    ("Attempts", f"{matched} matched / {attempts} total")
                )
            elif attempts is not None:
                rows.append(("Attempts", str(attempts)))

        regression_status = getattr(finding, "regression_status", None)
        if regression_status is not None:
            rows.append(("Regression", self._status_cell(regression_status)))

        regression_runs = getattr(finding, "regression_runs", None)
        if regression_runs is not None:
            rows.append(("Regression runs", str(regression_runs)))

        if not rows:
            return ""
        return "#### Reproduction\n\n" + self._render_kv_table(rows)

    @staticmethod
    def _status_cell(value: Any) -> str:
        """Return a table cell for a status value with a strong prefix."""
        text = str(value).strip()
        if not text:
            return _NOT_AVAILABLE
        lowered = text.lower()
        if lowered in ("reproduced", "passed"):
            return f"**{_escape_table_cell(text)}**"
        if lowered in ("not_reproduced", "failed"):
            return f"**{_escape_table_cell(text)}**"
        return _escape_table_cell(text)

    def _render_finding_evidence(self, finding: ReportFinding) -> str:
        if not self._options.include_raw_output:
            return ""
        raw = getattr(finding, "raw_output", None)
        if raw is None or not isinstance(raw, str) or not raw:
            return ""

        text, truncated = _truncate(raw, self._options.max_output_chars)
        block = _code_block(
            text,
            lang="",
            fence_char=self._options.fence_char,
        )

        truncated_notice = ""
        if truncated:
            truncated_notice = (
                f"> Output truncated at {self._options.max_output_chars:,} "
                "characters by the reporter.\n\n"
            )

        body = f"{truncated_notice}{block}"

        if self._options.use_details_blocks:
            return (
                "#### Evidence\n\n"
                "<details>\n"
                "<summary>Raw crash output</summary>\n\n"
                f"{body}\n\n"
                "</details>"
            )
        return "#### Evidence\n\n" + body

    def _render_finding_notes(self, finding: ReportFinding) -> str:
        notes = getattr(finding, "notes", None) or ()
        if not notes:
            return ""
        lines = ["#### Notes", ""]
        for note in notes:
            lines.append(f"- {_escape_text(note)}")
        return "\n".join(lines)

    def _render_finding_metadata(self, finding: ReportFinding) -> str:
        metadata = getattr(finding, "metadata", None)
        if not metadata:
            return ""
        try:
            text = json.dumps(
                dict(metadata),
                indent=2,
                sort_keys=True,
                default=str,
            )
        except Exception as exc:  # noqa: BLE001
            raise MarkdownSerializationError(
                f"failed to serialise finding metadata: {exc}"
            ) from exc

        block = _code_block(
            text, lang="json", fence_char=self._options.fence_char
        )

        if self._options.use_details_blocks:
            return (
                "#### Metadata\n\n"
                "<details>\n"
                "<summary>Additional metadata</summary>\n\n"
                f"{block}\n\n"
                "</details>"
            )
        return "#### Metadata\n\n" + block

