# KMCS Markdown Report
# ====================
#
# Documentation-friendly rendering of KMCS findings.
#
# This reporter serialises the reporting layer's canonical data model
# into GitHub-flavored Markdown. Where the HTML reporter produces a
# self-contained visual document and the JSON reporter produces a
# machine-readable interchange document, the Markdown reporter
# produces text that reads as well in a terminal as it does rendered
# on GitHub, in a wiki, or inside a research notebook.
#
# The design goals are:
#
#   * **Readable raw.** The output must be legible when viewed with
#     ``cat``, ``less``, or a plain text editor. Headings, tables,
#     lists, and fenced code blocks carry the structure; no raw HTML
#     is required to understand the document.
#
#   * **Readable rendered.** The same output must render cleanly on
#     GitHub, GitLab, Gitea, and any CommonMark-compliant renderer.
#     Tables use GFM syntax, collapsible sections use ``<details>``
#     (universally supported by these platforms), and code blocks
#     choose their fence length dynamically so that content
#     containing backticks never breaks out of its fence.
#
#   * **Faithful to the data model.** This reporter shares the same
#     :class:`ReportBundle` and :class:`ReportFinding` types that the
#     HTML and JSON reporters consume. It does not re-derive any
#     field from raw subsystem records; if the bundle does not carry
#     a value, the reporter writes "not available" — never a
#     fabricated default.
#
#   * **Stable.** Given the same bundle, the reporter produces
#     byte-identical output. Findings are ordered by severity (most
#     severe first) and then by discovery time (newest first). Table
#     rows, metadata keys, and the table of contents are all emitted
#     in a deterministic order.
#
#   * **Safe.** Every user-supplied string is escaped before being
#     written into a table cell, a heading, or a paragraph.
#     Pipe characters are escaped so they cannot break a table;
#     newlines inside cells become ``<br>``; the fence length of
#     every code block is chosen so that embedded backtick runs
#     cannot close the block early.
#
# Relationship to other reporters
# -------------------------------
#
# :mod:`kmcs.reporting.html` defines the shared data model and the
# factory functions that project analysis, reproduction, and
# regression records onto that model. This module imports those types
# and factories and does not redefine them. The result is that a
# change to how a finding is projected from a crash record affects
# all three reporters identically.
#
# What this module does not do
# ----------------------------
#
#   * It does not run the crash parser, the classifier, the severity
#     assigner, or the fingerprint extractor.
#
#   * It does not compute severity, coverage, or counts that were not
#     already present in the bundle.
#
#   * It does not modify its input. The bundle is read-only.
#
#   * It does not generate HTML. Where a Markdown-specific rendering
#     of a value is required (for example, a collapsible evidence
#     section), the reporter emits the minimum HTML necessary and
#     documents the choice inline.
#
# Document structure
# ------------------
#
# A typical rendered document has the following shape::
#
#     # Report title
#
#     *Subtitle*
#
#     <metadata table>
#
#     ---
#
#     ## Table of contents
#
#     - [Summary](#summary)
#     - [Campaign](#campaign)
#     - [Corpus](#corpus)
#     - [Findings](#findings)
#
#     ---
#
#     ## Summary
#
#     <counts table>
#
#     ---
#
#     ## Campaign
#
#     <campaign table>
#
#     ---
#
#     ## Corpus
#
#     <corpus table>
#
#     ---
#
#     ## Findings
#
#     ### Overview
#
#     <findings summary table>
#
#     ### [Critical] heap-buffer-overflow in parse_header
#
#     <finding detail sections>
#
#     ---
#
#     <supplemental sections>
#
#     ---
#
#     <report data (JSON) in a collapsible block>
#
#     ---
#
#     *Generated by KMCS 1.0.0 at 2026-01-01T00:00:00+00:00*
#
# Compatibility
# -------------
#
# Python 3.10+.

