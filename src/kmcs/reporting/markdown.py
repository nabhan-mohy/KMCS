def render_markdown(
    bundle: ReportBundle,
    *,
    options: Optional[MarkdownOptions] = None,
) -> str:
    """Render ``bundle`` to Markdown using the given options.

    This is a one-shot wrapper around :class:`MarkdownReporter` for
    callers who do not need to reuse a reporter instance.
    """
    reporter = MarkdownReporter(options)
    return reporter.render(bundle)


def dump_markdown_string(
    bundle: ReportBundle,
    *,
    options: Optional[MarkdownOptions] = None,
) -> str:
    """Alias for :func:`render_markdown`.

    Provided for symmetry with :mod:`kmcs.reporting.json_report`,
    which names its string-producing helper ``dump_json_string``.
    """
    return render_markdown(bundle, options=options)


def dump_markdown(
    bundle: ReportBundle,
    path: Union[str, os.PathLike[str]],
    *,
    options: Optional[MarkdownOptions] = None,
) -> Path:
    """Render ``bundle`` and write it to ``path`` atomically.

    Returns the absolute path of the written file.
    """
    reporter = MarkdownReporter(options)
    return reporter.write(bundle, path)


def write_markdown(
    bundle: ReportBundle,
    path: Union[str, os.PathLike[str]],
    *,
    options: Optional[MarkdownOptions] = None,
) -> Path:
    """Alias for :func:`dump_markdown`.

    Provided because callers who work with the HTML reporter
    naturally reach for ``write_html`` and expect a symmetric name.
    """
    return dump_markdown(bundle, path, options=options)


