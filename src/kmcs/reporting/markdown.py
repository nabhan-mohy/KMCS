def _format_datetime(value: Optional[datetime]) -> str:
    """Format a datetime for inclusion in Markdown.

    The ISO-8601 form is used because it sorts naturally, renders
    identically in every Markdown engine, and is unambiguous about
    the timezone. Naive datetimes are assumed to be UTC.
    """
    if value is None:
        return _NOT_AVAILABLE
    if not isinstance(value, datetime):
        return _escape_table_cell(value)
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    try:
        return value.isoformat(timespec="seconds")
    except Exception:  # noqa: BLE001
        return str(value)


def _format_bytes(value: Optional[int]) -> str:
    """Format a byte count as a human-readable string.

    The output is of the form ``"1.23 MiB (1290240 bytes)"``, showing
    both the human-readable and the exact value. The latter is
    important for archival accuracy.
    """
    if value is None:
        return _NOT_AVAILABLE
    try:
        n = int(value)
    except (TypeError, ValueError):
        return _escape_table_cell(value)
    if n < 1024:
        return f"{n} B"
    size = float(n)
    units = ["KiB", "MiB", "GiB", "TiB", "PiB"]
    for unit in units:
        size /= 1024.0
        if size < 1024.0:
            return f"{size:.2f} {unit} ({n:,} bytes)"
    return f"{n:,} bytes"


def _format_seconds(value: Optional[float]) -> str:
    """Format a duration in seconds."""
    if value is None:
        return _NOT_AVAILABLE
    try:
        s = float(value)
    except (TypeError, ValueError):
        return _escape_table_cell(value)
    if s < 1.0:
        return f"{s * 1000:.0f} ms"
    if s < 60.0:
        return f"{s:.2f} s"
    minutes, seconds = divmod(s, 60.0)
    if minutes < 60.0:
        return f"{int(minutes)}m {seconds:.0f}s"
    hours, minutes = divmod(minutes, 60.0)
    return f"{int(hours)}h {int(minutes)}m {seconds:.0f}s"


def _format_percent(value: Optional[float]) -> str:
    """Format a percentage value."""
    if value is None:
        return _NOT_AVAILABLE
    try:
        return f"{float(value):.2f} %"
    except (TypeError, ValueError):
        return _escape_table_cell(value)


def _severity_level_name(value: Any) -> str:
    """Normalise an arbitrary severity value to one of the canonical names."""
    if value is None:
        return "unknown"
    try:
        parsed = SeverityLevel.parse(value)
        name = getattr(parsed, "value", None)
        if isinstance(name, str):
            return name
    except Exception:  # noqa: BLE001
        pass
    text = str(value).strip().lower()
    if text in ("critical", "high", "medium", "low", "informational"):
        return text
    if text in ("info", "note", "informational"):
        return "informational"
    if text in ("severe",):
        return "high"
    if text in ("moderate", "med"):
        return "medium"
    return "unknown"


def _severity_badge(level_name: str) -> str:
    """Return a textual badge for a severity level.

    The badge uses uppercase text inside a bold marker rather than an
    emoji, so that it renders consistently across terminals, editors,
    and Markdown renderers.
    """
    display = {
        "critical": "CRITICAL",
        "high": "HIGH",
        "medium": "MEDIUM",
        "low": "LOW",
        "informational": "INFORMATIONAL",
        "unknown": "UNCLASSIFIED",
    }.get(level_name, "UNCLASSIFIED")
    return f"**\\[{display}\\]**"


def _truncate(text: str, limit: Optional[int]) -> Tuple[str, bool]:
    """Truncate ``text`` to ``limit`` characters; return (text, truncated)."""
    if limit is None or limit < 0 or len(text) <= limit:
        return text, False
    return text[:limit], True


def _slugify_anchor(text: str) -> str:
    """Return a URL-safe anchor for a Markdown heading.

    The rules are the ones GitHub uses: lowercase, replace spaces and
    non-alphanumeric characters with hyphens, collapse runs of
    hyphens, and trim leading and trailing hyphens. An empty result
    becomes ``"section"``.
    """
    slug = re.sub(r"[^a-zA-Z0-9\-]+", "-", text.lower())
    slug = re.sub(r"-+", "-", slug).strip("-")
    return slug or "section"


