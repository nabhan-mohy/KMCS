    # Title section
    # ------------------------------------------------------------------

    def _render_title(self, bundle: ReportBundle) -> str:
        md = bundle.metadata
        parts: List[str] = []
        parts.append(f"# {_heading_text(md.title)}")
        if md.subtitle:
            parts.append(f"*{_escape_text(md.subtitle)}*")

        rows: List[Tuple[str, str]] = []
        rows.append(("Generated at", _format_datetime(md.generated_at)))
        if md.generator:
            rows.append(("Generator", _escape_table_cell(md.generator)))
        if md.campaign_id:
            rows.append(("Campaign ID", _inline_code(md.campaign_id)))
        if md.campaign_name:
            rows.append(("Campaign", _escape_table_cell(md.campaign_name)))
        if md.fuzzer:
            rows.append(("Fuzzer", _inline_code(md.fuzzer)))
        if md.sanitizer:
            rows.append(("Sanitizer", _inline_code(md.sanitizer)))
        if md.target_description:
            rows.append(("Target", _inline_code(md.target_description)))

        if rows:
            parts.append(self._render_kv_table(rows))

        if md.notes:
            note_lines = [f"- {_escape_text(n)}" for n in md.notes]
            parts.append("\n".join(note_lines))

        return "\n\n".join(parts)

