# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

#: Default fence character for code blocks. Backticks are the
#: conventional choice and are recognised by every Markdown renderer
#: in common use. When the content of a block contains a run of
#: backticks, the reporter lengthens the fence rather than switching
#: characters, which is the behaviour specified by CommonMark.
DEFAULT_FENCE_CHAR: str = "`"

#: Minimum fence length. CommonMark requires at least three.
DEFAULT_FENCE: str = DEFAULT_FENCE_CHAR * 3

#: Default cap on the number of characters of raw crash output
#: rendered inline. Longer output is truncated and a marker is
#: appended. ``None`` disables the cap.
DEFAULT_MAX_OUTPUT_CHARS: Optional[int] = 40_000

#: Whether the table of contents is emitted by default.
DEFAULT_INCLUDE_TOC: bool = True

#: Whether the summary section is emitted by default.
DEFAULT_INCLUDE_SUMMARY: bool = True

#: Whether the underlying bundle is dumped as JSON in a collapsible
#: block at the end of the report.
DEFAULT_INCLUDE_METADATA_JSON: bool = True

#: Whether verbose content (raw output, metadata JSON, supplemental
#: bodies) is wrapped in ``<details>`` blocks. Disabling this produces
#: a flatter document that is easier to read in a terminal but
#: potentially very long.
DEFAULT_USE_DETAILS_BLOCKS: bool = True

#: Whether a trailing newline is appended to the rendered document.
DEFAULT_TRAILING_NEWLINE: bool = True

#: Placeholder rendered when a field is absent from the bundle. This
#: is intentionally italicised so that it is visually distinct from
#: values that happen to be short strings.
_NOT_AVAILABLE: str = "_not available_"

#: Severity ordering used when sorting findings. Lower numbers are
#: considered more severe.
_SEVERITY_ORDER: Mapping[str, int] = {
    "critical": 0,
    "high": 1,
    "medium": 2,
    "low": 3,
    "informational": 4,
    "unknown": 5,
}

#: Canonical names of the levels in :class:`SeverityLevel`. Kept as a
#: tuple so that iteration order is stable across Python versions.
_SEVERITY_LEVELS: Tuple[str, ...] = (
    "critical",
    "high",
    "medium",
    "low",
    "informational",
    "unknown",
)


