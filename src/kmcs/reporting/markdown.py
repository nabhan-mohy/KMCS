class MarkdownReporter:
    """Renders a :class:`ReportBundle` into Markdown.

    Parameters
    ----------
    options:
        Optional :class:`MarkdownOptions`. Defaults are used when
        omitted.

    Notes
    -----
    A reporter instance is stateless with respect to the bundle.
    Rendering the same bundle twice with the same options produces
    byte-identical output. Options are immutable, so a reporter may
    be shared safely across threads.
    """

    def __init__(self, options: Optional[MarkdownOptions] = None) -> None:
        self._options = options or MarkdownOptions()

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    @property
    def options(self) -> MarkdownOptions:
        return self._options

    def render(self, bundle: ReportBundle) -> str:
        """Render ``bundle`` to Markdown and return the resulting text.

        Raises
        ------
        MarkdownValidationError
            If the bundle fails pre-render validation.
        MarkdownSerializationError
            If a value in the bundle cannot be rendered.
        """
        if bundle is None:
            raise MarkdownValidationError("bundle must not be None")
        self._validate_bundle(bundle)

        sections: List[str] = []
        sections.append(self._render_title(bundle))
        if self._options.include_toc:
            toc = self._render_toc(bundle)
            if toc:
                sections.append(toc)
        if self._options.include_summary:
            sections.append(self._render_summary(bundle))
        if bundle.campaign is not None:
            sections.append(self._render_campaign(bundle.campaign))
        if bundle.corpus is not None:
            sections.append(self._render_corpus(bundle.corpus))
        if bundle.findings:
            sections.append(self._render_findings(bundle.findings))
        if bundle.supplemental_sections:
            sections.append(self._render_supplemental(bundle.supplemental_sections))
        if self._options.include_metadata_json:
            meta = self._render_metadata_json(bundle)
            if meta:
                sections.append(meta)
        sections.append(self._render_footer(bundle))

        text = "\n\n".join(s for s in sections if s)
        # Normalise any accidental multi-blank-line sequences.
        text = re.sub(r"\n{3,}", "\n\n", text)
        if self._options.trailing_newline and not text.endswith("\n"):
            text += "\n"
        return text

    def write(
        self,
        bundle: ReportBundle,
        path: Union[str, os.PathLike[str]],
    ) -> Path:
        """Render ``bundle`` and write it to ``path`` atomically.

        The file is written through a temporary sibling file, so that
        a partially-written report never appears on disk. Parent
        directories are created if necessary.

        Returns the absolute path of the written file.
        """
        target = Path(path).expanduser().resolve()
        target.parent.mkdir(parents=True, exist_ok=True)
        text = self.render(bundle)
        data = text.encode("utf-8")

        fd, tmp_name = tempfile.mkstemp(
            prefix=".kmcs-markdown-", dir=str(target.parent)
        )
        tmp_path = Path(tmp_name)
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
                fh.flush()
                try:
                    os.fsync(fh.fileno())
                except OSError:
                    pass
            os.replace(tmp_path, target)
        except Exception:
            try:
                tmp_path.unlink()
            except OSError:
                pass
            raise
        return target

    def write_stream(self, bundle: ReportBundle, stream: TextIO) -> None:
        """Write the rendered Markdown to an open text stream.

        The stream is not closed by this method.
        """
        stream.write(self.render(bundle))

    # ------------------------------------------------------------------
    # Bundle validation
    # ------------------------------------------------------------------

    def _validate_bundle(self, bundle: ReportBundle) -> None:
        """Reject bundles that would produce a malformed document."""
        metadata = getattr(bundle, "metadata", None)
        if metadata is None:
            raise MarkdownValidationError("bundle has no metadata")
        title = getattr(metadata, "title", None)
        if not isinstance(title, str) or not title.strip():
            raise MarkdownValidationError("bundle metadata has no title")

        seen: Dict[str, int] = {}
        findings = getattr(bundle, "findings", None) or ()
        for idx, finding in enumerate(findings):
            fid = getattr(finding, "finding_id", None)
            if not isinstance(fid, str) or not fid:
                raise MarkdownValidationError(
                    f"finding at index {idx} has no identifier"
                )
            if fid in seen:
                raise MarkdownValidationError(
                    f"duplicate finding identifier {fid!r} "
                    f"(indices {seen[fid]} and {idx})"
                )
            seen[fid] = idx

